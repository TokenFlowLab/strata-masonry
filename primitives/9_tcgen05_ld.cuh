// 9_tcgen05_ld.cuh -- tcgen05.ld.sync.aligned.<shape>.<num>{.pack::16b}.b32
//                     {dst}, [taddr]
//                     [, immHalfSplitoff for shape .16x32bx2]
//                  -- tcgen05.ld.red.sync.aligned.32x32b.<num>.<redOp>{.abs}
//                     {.NaN}.<type> {dst}, redval, [taddr]
//
// ARCH: sm_100a (.ld.red is sm_103a+; gated internally by __CUDA_ARCH__)
//
// Warp-collective asynchronous load from TMEM into registers.
//
// COVERAGE MATRIX (per PTX 9.7.18.8.3, complete; same grid for the
// .pack::16b variants). Y = wrapper provided; - = combination not
// defined by PTX:
//
//   shape    | x1 | x2 | x4 | x8 | x16 | x32 | x64 | x128
//   ---------|----|----|----|----|-----|-----|-----|-----
//   32x32b   |  Y |  Y |  Y |  Y |  Y  |  Y  |  Y  |  Y
//   16x32bx2 |  Y |  Y |  Y |  Y |  Y  |  Y  |  Y  |  Y    (+ immHalfSplitoff)
//   16x64b   |  Y |  Y |  Y |  Y |  Y  |  Y  |  Y  |  Y
//   16x128b  |  Y |  Y |  Y |  Y |  Y  |  Y  |  Y  |  -
//   16x256b  |  Y |  Y |  Y |  Y |  Y  |  Y  |  -  |  -
//
// Regs/thread per cell (= shape's row scaling x .num):
//
//   shape    | x1 | x2 | x4 | x8 | x16 | x32 | x64 | x128
//   ---------|----|----|----|----|-----|-----|-----|-----
//   32x32b   |  1 |  2 |  4 |  8 |  16 |  32 |  64 | 128
//   16x32bx2 |  1 |  2 |  4 |  8 |  16 |  32 |  64 | 128
//   16x64b   |  1 |  2 |  4 |  8 |  16 |  32 |  64 | 128
//   16x128b  |  2 |  4 |  8 | 16 |  32 |  64 | 128 |  -
//   16x256b  |  4 |  8 | 16 | 32 |  64 | 128 |   - |  -
//
// Total wrappers: 79 (37 dense + 37 pack16b + 5 ld.red).
//
// Completion is tracked by tcgen05.wait::ld (see #12). Every warp
// issues the same call; the warp's lane ID within the warpgroup
// selects which 32 of the 128 TMEM lanes it reads.
//
// Variants:
//   tcgen05_ld_<shape>_x<N>(taddr, regs)           regular .b32
//   tcgen05_ld_<shape>_x<N>_pack16b(taddr, regs)   .pack::16b (FP16/BF16)
//   tcgen05_ld_16x32bx2_x<N><IMM>(taddr, regs)     shape2 with immHalfSplitoff
//   tcgen05_ld_red_32x32b_<op>_<type>_x2           reduction load (sm_103a+)
//
// Argument convention: x1 takes uint32_t&; x2 takes two uint32_t&; x4+
// takes uint32_t (&)[N]. Caller-side: declare uint32_t regs[N] and pass.
//
// .pack::16b packs two 16-bit elements from adjacent columns into a single
// 32-bit register on load (use when staging FP16/BF16 from TMEM
// accumulators into stmatrix-compatible registers).
//
// .ld.red is supported on sm_101a / sm_103f / sm_110f only. The wrappers
// emit the asm conditionally on `__CUDA_ARCH__ >= 1030` so dual-gencode
// builds that target sm_100a fall back compile cleanly (output regs are
// undefined for the unreached path).
//
// Issuer: every thread in the warp executes the same instruction
// collectively (.sync.aligned). All lanes must pass the same taddr.
// Source: knowledge/instructions/tmem/tcgen05_tmem.md
// PTX:    9.7.18.8.3 (tcgen05.ld + Table 61 shape x num)
//
#include <cstdint>

// ===========================================================================
// .32x32b family -- N regs/thread for .xN. Standard FP32 epilogue read.
