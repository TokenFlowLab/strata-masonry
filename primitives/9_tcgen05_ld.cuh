// tcgen05.ld.red -- floating-point/integer reduction load. Reduces values
// across columns in each lane and writes both the destination register and
// the reduction result. Per PTX 9.7.18.8.3 syntax:
//
//   tcgen05.ld.red.sync.aligned.shape3.num.redOp{.abs}{.NaN}.f32 r, redval, [taddr];
//   tcgen05.ld.red.sync.aligned.shape3.num.redOp.type      r, redval, [taddr];
//
// .shape3 = { .32x32b }; .num must be at least .x2.
//
// Per ISA Target Notes, tcgen05.ld.red is supported on sm_101a (renamed to
// sm_110a) and on family-specific sm_103f / sm_110f. NOT supported on
// sm_100a (GB200). The wrapper exists at all build targets where the file
// is included, but the asm body is gated by __CUDA_ARCH__ >= 1030 so that
// dual-gencode fallbacks to sm_100a get an empty body (output regs are
// undefined for the unreached path).
// ===========================================================================

__device__ __forceinline__ void tcgen05_ld_red_32x32b_min_f32_x2(
    uint32_t tmem_addr, float& redval, uint32_t& r0, uint32_t& r1) {
#if __CUDA_ARCH__ >= 1030
  asm volatile(
    "tcgen05.ld.red.sync.aligned.32x32b.x2.min.f32 {%0, %1}, %2, [%3];\n"
    : "=r"(r0), "=r"(r1), "+f"(redval) : "r"(tmem_addr));
#else
  (void)tmem_addr; (void)redval; r0 = 0; r1 = 0;
#endif
}

