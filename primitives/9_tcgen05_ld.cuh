__device__ __forceinline__ void tcgen05_ld_32x32b_x1(
    uint32_t tmem_addr, uint32_t& r0) {
  asm volatile("tcgen05.ld.sync.aligned.32x32b.x1.b32 {%0}, [%1];\n"
               : "=r"(r0) : "r"(tmem_addr));
}

