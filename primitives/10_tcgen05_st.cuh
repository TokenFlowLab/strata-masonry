// 10_tcgen05_st.cuh -- tcgen05.st.sync.aligned.<shape>.<num>{.unpack::16b}.b32
//                      [taddr], {src}
//                      [, immHalfSplitoff for shape .16x32bx2]
//
// ARCH: sm_100a
//
// Warp-collective asynchronous store from registers into TMEM.
//
// COVERAGE MATRIX (per PTX 9.7.18.8.4, complete; same grid for the
// .unpack::16b variants). Y = wrapper provided; - = combination not
// defined by PTX:
//
//   shape    | x1 | x2 | x4 | x8 | x16 | x32 | x64 | x128
//   ---------|----|----|----|----|-----|-----|-----|-----
//   32x32b   |  Y |  Y |  Y |  Y |  Y  |  Y  |  Y  |  Y
//   16x32bx2 |  Y |  Y |  Y |  Y |  Y  |  Y  |  Y  |  Y    (+ immHalfSplitoff)
//   16x64b   |  Y |  Y |  Y |  Y |  Y  |  Y  |  Y  |  Y
//   16x128b  |  Y |  Y |  Y |  Y |  Y  |  Y  |  Y  |  -
//   16x256b  |  Y |  Y |  Y |  Y |  Y  |  Y  |  -  |  -
//
// Regs/thread per cell (= shape's row scaling x .num):
//
//   shape    | x1 | x2 | x4 | x8 | x16 | x32 | x64 | x128
//   ---------|----|----|----|----|-----|-----|-----|-----
//   32x32b   |  1 |  2 |  4 |  8 |  16 |  32 |  64 | 128
//   16x32bx2 |  1 |  2 |  4 |  8 |  16 |  32 |  64 | 128
//   16x64b   |  1 |  2 |  4 |  8 |  16 |  32 |  64 | 128
//   16x128b  |  2 |  4 |  8 | 16 |  32 |  64 | 128 |  -
//   16x256b  |  4 |  8 | 16 | 32 |  64 | 128 |   - |  -
//
// Total wrappers: 74 (37 dense + 37 unpack16b).
//
// Completion is tracked by tcgen05.wait::st (see #12). Used to preload
// accumulators, scale factors, or bias into TMEM before a tcgen05.mma
// issue.
//
// Variants:
//   tcgen05_st_<shape>_x<N>(taddr, regs)             regular .b32
//   tcgen05_st_<shape>_x<N>_unpack16b(taddr, regs)   .unpack::16b
//   tcgen05_st_16x32bx2_x<N><IMM>(taddr, regs)       shape2 with immHalfSplitoff
//
// Argument convention: x1 takes uint32_t; x2 takes two uint32_t; x4+
// takes const uint32_t (&)[N].
//
// .unpack::16b unpacks each 32-bit source register into two 16-bit TMEM
// cells (adjacent columns). Use when staging FP16/BF16 data into TMEM
// for an MMA issue; omit for FP32/INT32.
//
// Issuer: every thread in the warp executes the same instruction
// collectively (.sync.aligned). All lanes must pass the same taddr.
// Source: knowledge/instructions/tmem/tcgen05_tmem.md
// PTX:    9.7.18.8.4 (tcgen05.st + Table 63 shape x num)
//
#include <cstdint>

// ===========================================================================
