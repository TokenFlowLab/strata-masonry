__device__ __forceinline__ void tcgen05_st_32x32b_x1(
    uint32_t tmem_addr, uint32_t r0) {
  asm volatile("tcgen05.st.sync.aligned.32x32b.x1.b32 [%0], {%1};\n"
               :: "r"(tmem_addr), "r"(r0));
}

